"""The only module that writes password hashes (PWD-001, PWD-021).

Every path that sets a password (user create, reset, change, first login, seed, tools) calls here, so the
active policy is enforced in exactly one place.
"""
from __future__ import annotations

from datetime import timedelta

from sqlalchemy import delete, select
from sqlalchemy.orm import Session

from app.core.clock import Clock
from app.core.errors import invalid
from app.core.security import hash_password, verify_password
from app.models.identity import PasswordHistory, User
from app.services.policy_service import MAX_HISTORY, PasswordPolicyService, add_months, evaluate, generate


class CredentialService:
    def __init__(self, session: Session, clock: Clock, policy: PasswordPolicyService) -> None:
        self._session = session
        self._clock = clock
        self._policy = policy

    # -- generation ---------------------------------------------------------------------------------
    def generate_password(self, username: str = "") -> str:
        """PWD-020: generated by the active policy, then validated by the same rules."""
        return generate(self._policy.get(), username)

    # -- new users ----------------------------------------------------------------------------------
    def hash_for_new_user(self, username: str, password: str) -> str:
        """Validate a password for a user that does not exist yet and return its hash."""
        failures = evaluate(self._policy.get(), password, username)
        if failures:
            raise invalid("password.rejected", failures)
        return hash_password(password)

    def apply_to_new_user(self, user: User, password: str, *, must_change: bool = True) -> None:
        now = self._clock.now()
        policy = self._policy.get()
        user.password_hash = self.hash_for_new_user(user.username, password)
        user.password_changed_at = now
        user.password_expires_at = (
            add_months(now, policy.expiration_months) if policy.expiration_enabled else None
        )
        user.must_change_password = must_change

    # -- existing users -----------------------------------------------------------------------------
    def set_password(
        self,
        user: User,
        new_password: str,
        *,
        admin_set: bool = False,
        voluntary: bool = False,
        must_change_next: bool = False,
    ) -> None:
        """Change the password of an existing user and enforce every rule of the active policy.

        admin_set: set by an administrator or generated by the system (history rule may differ).
        voluntary: a user-initiated change, subject to the minimum age. Forced changes are not.
        """
        policy = self._policy.get()
        now = self._clock.now()
        failures = evaluate(policy, new_password, user.username)

        if verify_password(new_password, user.password_hash):
            failures.append("password.same_as_current")
        elif policy.history_count > 0 and (not admin_set or policy.history_applies_to_admin_set):
            previous = self._session.execute(
                select(PasswordHistory.password_hash)
                .where(PasswordHistory.user_id == user.id)
                .order_by(PasswordHistory.created_at.desc(), PasswordHistory.id.desc())
                .limit(policy.history_count)
            ).scalars()
            if any(verify_password(new_password, h) for h in previous):
                failures.append("password.reused")

        if (
            voluntary
            and policy.min_age_hours > 0
            and user.password_changed_at is not None
            and not user.must_change_password
            and now - user.password_changed_at < timedelta(hours=policy.min_age_hours)
        ):
            failures.append("password.too_recent")

        if failures:
            raise invalid("password.rejected", failures)

        # Keep the outgoing hash in the history, then replace.
        self._session.add(
            PasswordHistory(user_id=user.id, password_hash=user.password_hash, created_at=now)
        )
        user.password_hash = hash_password(new_password)
        user.password_changed_at = now
        user.password_expires_at = (
            add_months(now, policy.expiration_months) if policy.expiration_enabled else None
        )
        user.must_change_password = must_change_next
        self._trim_history(user.id)

    def _trim_history(self, user_id: int) -> None:
        self._session.flush()
        keep = self._session.execute(
            select(PasswordHistory.id)
            .where(PasswordHistory.user_id == user_id)
            .order_by(PasswordHistory.created_at.desc(), PasswordHistory.id.desc())
            .limit(MAX_HISTORY)
        ).scalars().all()
        if keep:
            self._session.execute(
                delete(PasswordHistory).where(PasswordHistory.user_id == user_id, PasswordHistory.id.not_in(keep))
            )
